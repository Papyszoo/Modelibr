using Application.Abstractions;
using Application.Abstractions.Messaging;
using Application.Abstractions.Repositories;
using Application.Abstractions.Services;
using Application.Abstractions.Storage;
using Domain.Services;
using Domain.ValueObjects;
using SharedKernel;

namespace Application.Thumbnails;

/// <summary>
/// Re-queues generation for every thumbnail whose stored file is missing on disk.
/// </summary>
/// <remarks>
/// Run after a restore: a backup that left thumbnails out brings back thumbnail
/// rows that still claim to be ready while their files are gone. It reuses the
/// ordinary queue entry points, so a re-queued thumbnail is regenerated by the
/// same jobs and the same worker path as any other. A thumbnail whose file is
/// present is left completely alone - restoring an archive that carried
/// thumbnails therefore queues nothing.
/// </remarks>
public record RequeueMissingThumbnailsCommand : ICommand<RequeueMissingThumbnailsResponse>;

public record RequeueMissingThumbnailsResponse(int EnqueuedCount);

internal sealed class RequeueMissingThumbnailsCommandHandler
    : ICommandHandler<RequeueMissingThumbnailsCommand, RequeueMissingThumbnailsResponse>
{
    private readonly IModelRepository _modelRepository;
    private readonly IThumbnailRepository _thumbnailRepository;
    private readonly ITextureSetRepository _textureSetRepository;
    private readonly IEnvironmentMapRepository _environmentMapRepository;
    private readonly IVfxRepository _vfxRepository;
    private readonly IThumbnailQueue _thumbnailQueue;
    private readonly IUploadPathProvider _pathProvider;
    private readonly IDateTimeProvider _dateTimeProvider;
    private readonly IUnitOfWork _unitOfWork;

    public RequeueMissingThumbnailsCommandHandler(
        IModelRepository modelRepository,
        IThumbnailRepository thumbnailRepository,
        ITextureSetRepository textureSetRepository,
        IEnvironmentMapRepository environmentMapRepository,
        IVfxRepository vfxRepository,
        IThumbnailQueue thumbnailQueue,
        IUploadPathProvider pathProvider,
        IDateTimeProvider dateTimeProvider,
        IUnitOfWork unitOfWork)
    {
        _modelRepository = modelRepository;
        _thumbnailRepository = thumbnailRepository;
        _textureSetRepository = textureSetRepository;
        _environmentMapRepository = environmentMapRepository;
        _vfxRepository = vfxRepository;
        _thumbnailQueue = thumbnailQueue;
        _pathProvider = pathProvider;
        _dateTimeProvider = dateTimeProvider;
        _unitOfWork = unitOfWork;
    }

    public async Task<Result<RequeueMissingThumbnailsResponse>> Handle(
        RequeueMissingThumbnailsCommand command,
        CancellationToken cancellationToken)
    {
        var enqueued = 0;
        var now = _dateTimeProvider.UtcNow;

        // Model thumbnails. Retrieved per version because the aggregate returned by
        // GetAllAsync is detached and its Thumbnail navigation can be stale.
        foreach (var model in await _modelRepository.GetAllAsync(cancellationToken))
        {
            foreach (var version in model.Versions)
            {
                var thumbnail = await _thumbnailRepository
                    .GetByModelVersionIdAsync(version.Id, cancellationToken);

                if (thumbnail is null || thumbnail.Status != ThumbnailStatus.Ready) continue;
                if (!IsMissing(thumbnail.ThumbnailPath) && !IsMissing(thumbnail.PngThumbnailPath)) continue;

                var primaryFile = version.Files.FirstOrDefault();
                if (primaryFile is null) continue;

                // The file is gone but the row still says Ready, so the status
                // endpoint would report a thumbnail the file endpoint 404s on. Put
                // it back to Pending before the job is queued, exactly as a manual
                // regenerate does.
                thumbnail.Reset(now);
                await _thumbnailRepository.UpdateAsync(thumbnail, cancellationToken);

                await _thumbnailQueue.EnqueueAsync(
                    model.Id,
                    version.Id,
                    primaryFile.Sha256Hash,
                    forceRegenerate: true,
                    cancellationToken: cancellationToken);
                enqueued++;
            }
        }

        foreach (var textureSet in await _textureSetRepository.GetAllAsync(cancellationToken))
        {
            if (!IsMissing(textureSet.ThumbnailPath) && !IsMissing(textureSet.PngThumbnailPath)) continue;

            await _thumbnailQueue.EnqueueTextureSetThumbnailAsync(
                textureSet.Id, forceRegenerate: true, cancellationToken: cancellationToken);
            enqueued++;
        }

        foreach (var environmentMap in await _environmentMapRepository.GetAllAsync(cancellationToken))
        {
            foreach (var variant in environmentMap.Variants.Where(v => !v.IsDeleted))
            {
                if (!IsMissing(variant.ThumbnailPath)) continue;

                await _thumbnailQueue.EnqueueEnvironmentMapThumbnailAsync(
                    environmentMap.Id, variant.Id, forceRegenerate: true, cancellationToken: cancellationToken);
                enqueued++;
            }
        }

        foreach (var vfx in await _vfxRepository.GetAllAsync(cancellationToken))
        {
            if (!IsMissing(vfx.ThumbnailPath)) continue;

            await _thumbnailQueue.EnqueueVfxThumbnailAsync(
                vfx.Id, forceRegenerate: true, cancellationToken: cancellationToken);
            enqueued++;
        }

        // Persist the status resets staged above. The queue commits its own job
        // rows as it enqueues, but the thumbnail updates are ours to commit.
        await _unitOfWork.SaveChangesAsync(cancellationToken);

        return Result.Success(new RequeueMissingThumbnailsResponse(enqueued));
    }

    // A thumbnail with no recorded path has nothing to regenerate from; one whose
    // path is recorded but whose file is gone is exactly what this re-queues.
    // A path that cannot be resolved inside the uploads root (a malformed or
    // hostile stored value) is treated as missing so it is regenerated into a
    // fresh, safe path rather than failing the whole re-queue.
    private bool IsMissing(string? storedPath)
    {
        if (string.IsNullOrWhiteSpace(storedPath)) return false;
        try
        {
            return !File.Exists(_pathProvider.Resolve(storedPath));
        }
        catch (InvalidOperationException)
        {
            return true;
        }
    }
}
