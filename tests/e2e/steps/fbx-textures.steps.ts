import { createBdd } from "playwright-bdd";
import { expect } from "@playwright/test";
import { getScenarioState } from "../fixtures/shared-state";
import { UniqueFileGenerator } from "../fixtures/unique-file-generator";
import { ApiHelper } from "../helpers/api-helper";
import { ModelListPage } from "../pages/ModelListPage";

const { Given, When } = createBdd();

const API_BASE = process.env.API_BASE_URL || "http://localhost:8090";
const apiHelper = new ApiHelper(API_BASE);

const MODEL_KEY = "fbx-textures:model";

interface FbxModel {
    id: number;
    name: string;
}

Given("a textured FBX model exists", async ({ page }) => {
    // textured-cube.fbx is generated by fixtures/make-textured-fbx.py: a binary
    // FBX whose packed texture is embedded in its Content property. UniqueFileGenerator
    // copies FBX unchanged, which is fine on the fresh stack this scenario runs on.
    const filePath = await UniqueFileGenerator.generate("textured-cube.fbx", {
        uniqueFilename: true,
    });
    const uploaded = await apiHelper.uploadModel(filePath);
    const response = await page.request.get(`${API_BASE}/models/${uploaded.id}`);
    expect(
        response.ok(),
        `The uploaded FBX could not be read: ${response.status()}`,
    ).toBe(true);
    const model = await response.json();
    getScenarioState(page).setCustom<FbxModel>(MODEL_KEY, {
        id: uploaded.id,
        name: String(model.name),
    });
});

When("I open the textured FBX in the viewer", async ({ page }) => {
    const found = getScenarioState(page).getCustom<FbxModel>(MODEL_KEY);
    if (!found) {
        throw new Error("No textured FBX model was provisioned.");
    }
    const list = new ModelListPage(page);
    await list.openModel(found.name);
});
